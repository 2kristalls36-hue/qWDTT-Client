/**
 * The handwritten «Client» of the app icon, drawn lighter than in the icon: the letters
 * lose a thin band along their edges and the wave under them is a finer line. Drawn in
 * black; the caller colours it (the title lays the level colour over it).
 */
@Composable
internal fun ClientScript(modifier: Modifier = Modifier) {
    // The letters of the icon overlap one another; merged into one outline first, so the
    // thinning below follows only the outer edge and leaves no seams inside the word.
    val letters = remember {
        val raw = PathParser().parsePathString(CLIENT_LETTERS).toPath()
        androidx.compose.ui.graphics.Path().apply {
            op(raw, androidx.compose.ui.graphics.Path(), androidx.compose.ui.graphics.PathOperation.Union)
        }
    }
    val wave = remember { PathParser().parsePathString(CLIENT_WAVE).toPath() }
    Canvas(modifier) {
        // The icon's 64-unit box, its offset and its slant (as in ic_tile_lite.xml).
        val k = size.minDimension / 64f
        withTransform({
            scale(k, k, pivot = androidx.compose.ui.geometry.Offset.Zero)
            translate(-22f, -15f)
            rotate(-6f, pivot = androidx.compose.ui.geometry.Offset(54f, 50f))
        }) {
            drawPath(letters, Color.Black)
            // Thinner strokes: erase a band along every edge of the letters.
            drawPath(letters, Color.Black, style = Stroke(width = 1.15f), blendMode = BlendMode.Clear)
            drawPath(wave, Color.Black, style = Stroke(width = 2.0f, cap = StrokeCap.Round))
        }
    }
}

